        }

        doc.addEventListener('click', function (event) {
            if (!mobileNav || !hamburger || !mobileNav.classList.contains('open')) return;
            if (header && !header.contains(event.target)) closeMobileNav();
        });

        doc.addEventListener('keydown', function (event) {
            if (event.key === 'Escape') closeMobileNav();
        });
    }

    function finishLoading() {
        if (loaderFinished) return;
        loaderFinished = true;

        syncHeaderOffset();
        updateScrollUI();
        body.classList.add('gmi-page-ready');

        var currentTime = (window.performance && performance.now) ? performance.now() : Date.now();
        var minimumVisibleTime = 1100;
        var remainingTime = Math.max(0, minimumVisibleTime - (currentTime - loaderStartedAt));

        window.setTimeout(function () {
            if (loader) loader.classList.add('gmi-loaded');
            body.classList.remove('gmi-loading');
            root.classList.remove('gmi-loading-root');
            root.style.background = '';

            window.setTimeout(function () {
                if (loader && loader.parentNode) loader.parentNode.removeChild(loader);
            }, 850);
        }, remainingTime);
    }

    assignRevealDelays();
    prepareScrollImages();
    bindInteractions();

    doc.addEventListener('DOMContentLoaded', function () {
        syncHeaderOffset();
        updateScrollUI();
        initRevealAnimations();
        initScrollImageAnimations();
        body.classList.add('gmi-page-ready');
    }, { once: true });

    window.addEventListener('load', finishLoading, { once: true });
    window.addEventListener('scroll', requestScrollUpdate, { passive: true });
    window.addEventListener('resize', requestResizeUpdate, { passive: true });
    window.addEventListener('orientationchange', requestResizeUpdate, { passive: true });

    if ('ResizeObserver' in window && header) {
        new ResizeObserver(function () {
            window.requestAnimationFrame(syncHeaderOffset);
        }).observe(header);
    }

    if (doc.readyState === 'complete') finishLoading();

    /* Safety fallback: never leave the page covered if an external asset stalls. */
    window.setTimeout(finishLoading, 7000);
})();
