        (function () {
            'use strict';

            const body = document.body;
            const loader = document.getElementById('loader-wrapper');
            const loaderStartedAt = (window.performance && performance.now) ? performance.now() : Date.now();
            const minimumLoaderTime = 1100;
            let loaderFinished = false;
            const progressBar = document.getElementById('gmiProgressBar');
            const header = document.querySelector('.gmi-custom-header');
            const hamburger = document.querySelector('.gmi-hamburger');
            const mobileNav = document.getElementById('gmiNavMobile');
            let ticking = false;

            function syncHeaderOffset() {
                if (header) {
                    body.style.paddingTop = header.offsetHeight + 'px';
                }
            }

            function updateScrollUI() {
                const scrollTop = window.pageYOffset || document.documentElement.scrollTop;
                const scrollable = Math.max(1, document.documentElement.scrollHeight - window.innerHeight);

                if (progressBar) {
                    progressBar.style.width = Math.min(100, (scrollTop / scrollable) * 100) + '%';
                }

                if (header) {
                    header.classList.toggle('gmi-header-scrolled', scrollTop > 40);
                }

                ticking = false;
            }

            function requestScrollUpdate() {
                if (!ticking) {
                    window.requestAnimationFrame(updateScrollUI);
                    ticking = true;
                }
            }

            window.toggleMobileNav = function () {
                if (!mobileNav || !hamburger) return;
                const open = mobileNav.classList.toggle('open');
                hamburger.setAttribute('aria-expanded', String(open));
                syncHeaderOffset();
            };

            if ('IntersectionObserver' in window) {
                const observer = new IntersectionObserver(function (entries, currentObserver) {
                    entries.forEach(function (entry) {
                        if (entry.isIntersecting) {
                            entry.target.classList.add('active');
                            currentObserver.unobserve(entry.target);
                        }
                    });
                }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

                document.querySelectorAll('.reveal').forEach(function (element) {
                    observer.observe(element);
                });
            } else {
                document.querySelectorAll('.reveal').forEach(function (element) {
                    element.classList.add('active');
                });
            }

            document.querySelectorAll('#gmiNavMobile a').forEach(function (link) {
                link.addEventListener('click', function () {
                    if (mobileNav) mobileNav.classList.remove('open');
                    if (hamburger) hamburger.setAttribute('aria-expanded', 'false');
                    syncHeaderOffset();
                });
            });

            window.addEventListener('scroll', requestScrollUpdate, { passive: true });
            window.addEventListener('resize', syncHeaderOffset, { passive: true });

            function finishLoader() {
                if (loaderFinished) return;
                loaderFinished = true;

                const currentTime = (window.performance && performance.now) ? performance.now() : Date.now();
                const elapsed = currentTime - loaderStartedAt;
                const remaining = Math.max(0, minimumLoaderTime - elapsed);

                window.setTimeout(function () {
                    if (loader) {
                        loader.classList.add('gmi-loaded');
                        loader.classList.add('hide');
                    }

                    body.classList.remove('gmi-loading');
                    document.documentElement.classList.remove('gmi-loading-root');
                    document.documentElement.style.background = '';

                    window.setTimeout(function () {
                        if (loader && loader.parentNode) {
                            loader.parentNode.removeChild(loader);
                        }
                    }, 850);
                }, remaining);
            }

            window.addEventListener('load', function () {
                syncHeaderOffset();
                updateScrollUI();
                finishLoader();
            }, { once: true });

            /* Safety fallback for a stalled third-party resource. */
            window.setTimeout(finishLoader, 7000);

            syncHeaderOffset();
            updateScrollUI();
        }());
